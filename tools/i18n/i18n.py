#!/usr/bin/env python3
"""Firmware translations.

  python3 tools/i18n/i18n.py          update en.tsv (new strings appended, empty)
                                      and regenerate src/i18n_en.h
  python3 tools/i18n/i18n.py --check  list missing translations and printf mismatches

en.tsv: one line per string, "italian<TAB>english", with C escape sequences
(\\n, \\xE2\\x80\\xA2, \\") written exactly as in the sources. The Italian text
is the key: every TR("...") in the firmware is looked up by its hash.
"""
import os, re, sys, glob
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
TSV = os.path.join(HERE, 'en.tsv')
OUT = os.path.join(ROOT, 'src', 'i18n_en.h')

LIT = r'"(?:[^"\\\n]|\\.)*"'
TR_RE = re.compile(r'\bTR\(\s*((?:' + LIT + r'\s*)+)\)')

def c_bytes(lit_seq):
    """Bytes of a sequence of adjacent C string literals."""
    out = bytearray()
    for lit in re.findall(LIT, lit_seq):
        s = lit[1:-1]
        i = 0
        while i < len(s):
            c = s[i]
            if c != '\\':
                out += c.encode('utf-8'); i += 1; continue
            n = s[i + 1]
            if n == 'x':
                j = i + 2
                while j < len(s) and s[j] in '0123456789abcdefABCDEF': j += 1
                out.append(int(s[i + 2:j], 16) & 0xFF); i = j
            elif n in '01234567':
                j = i + 1
                while j < len(s) and j < i + 4 and s[j] in '01234567': j += 1
                out.append(int(s[i + 1:j], 8) & 0xFF); i = j
            else:
                out += {'n': b'\n', 't': b'\t', '"': b'"', '\\': b'\\', "'": b"'", 'r': b'\r', '0': b'\0'}.get(n, n.encode()); i += 2
    return bytes(out)

def fnv(b):
    h = 2166136261
    for x in b:
        h = ((h ^ x) * 16777619) & 0xFFFFFFFF
    return h

def source_strings():
    seen = {}
    files = glob.glob(os.path.join(ROOT, 'src', '**', '*.cpp'), recursive=True) + [os.path.join(ROOT, 'FlacPlayer.ino')]
    for f in sorted(files):
        if '/lvgl/' in f: continue
        txt = open(f, encoding='utf-8').read()
        for m in TR_RE.finditer(txt):
            seq = m.group(1)
            key = ''.join(l[1:-1] for l in re.findall(LIT, seq))   # as written in the source
            seen.setdefault(key, os.path.relpath(f, ROOT))
    return seen

SPEC = re.compile(r'%[-+ #0]*\d*(?:\.\d+)?(?:hh|h|ll|l|z)?[diouxXsc%]')

def spec_mismatch(it, en):
    """The translation must use the same printf placeholders, in the same order."""
    return en and SPEC.findall(it) != SPEC.findall(en)

def load_tsv():
    rows = []
    if os.path.exists(TSV):
        for line in open(TSV, encoding='utf-8'):
            line = line.rstrip('\n')
            if not line or line.startswith('#'): continue
            it, _, en = line.partition('\t')
            rows.append((it, en))
    return rows

def main():
    src = source_strings()
    rows = load_tsv()
    have = {it for it, _ in rows}
    new = [k for k in src if k not in have]
    unused = [it for it, _ in rows if it not in src]
    if '--check' in sys.argv:
        missing = [it for it, en in rows if it in src and not en] + new
        bad = [(it, en) for it, en in rows if spec_mismatch(it, en)]
        for m in missing: print('missing:', m)
        for it, en in bad: print('placeholders differ:', it, '|', en)
        for u in unused: print('unused:', u)
        sys.exit(1 if missing or bad else 0)
    with open(TSV, 'w', encoding='utf-8') as f:
        f.write('# italian<TAB>english - maintained by tools/i18n/i18n.py\n')
        for it, en in rows:
            if it in src: f.write(it + '\t' + en + '\n')
        for k in new: f.write(k + '\t\n')
    table = {}
    for it, en in load_tsv():
        if not en: continue
        if spec_mismatch(it, en): sys.exit('printf placeholders differ: %r / %r' % (it, en))
        h = fnv(c_bytes('"' + it + '"'))
        if h in table and table[h][0] != it: sys.exit('hash collision: %r / %r' % (it, table[h][0]))
        table[h] = (it, en)
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/i18n/i18n.py from tools/i18n/en.tsv: do not edit by hand.\n')
        f.write('const Entry kEn[] = {\n')
        for h in sorted(table):
            en = table[h][1]
            f.write('    {0x%08xu, "%s"},\n' % (h, en))
        if not table: f.write('    {0u, ""},\n')
        f.write('};\n')
    print('%d strings, %d translated, %d new, %d unused' % (len(src), len(table), len(new), len(unused)))

main()
